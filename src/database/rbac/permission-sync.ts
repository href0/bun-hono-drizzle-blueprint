import { eq, inArray, isNull } from 'drizzle-orm';
import {
  registryProblems,
  SYSTEM_ROLES,
  type PermissionDefinition,
} from '../../core/security/rbac';
import { BaseRepository } from '../base.repository';
import { permissions, roles, type Permission } from '../schema';
import { nowInstant } from '../../utils/datetime.util';
import { defaultTxHost, type TransactionHost } from '../transaction-host';

/** A registry the sync refuses (nothing was written); the CLI prints the message as is. */
export class PermissionRegistryError extends Error {}

export interface PermissionSyncResult {
  /** Registry keys inserted. */
  added: string[];
  /** Live API permissions whose label or group changed. */
  updated: string[];
  /** API permissions no longer in the registry: `retired_at` set (D67), never deleted. */
  retired: string[];
  /** Retired API permissions back in the registry: `retired_at` cleared. */
  restored: string[];
  /** System roles that were missing (a project whose migrations were regenerated by setup). */
  rolesCreated: string[];
}

/** Writes go through BaseRepository: actor `system` outside a request, updates audited (D16). */
class SyncPermissionsRepository extends BaseRepository<typeof permissions> {
  constructor(txHost: TransactionHost) {
    super(permissions, txHost);
  }

  /** Every live API permission, locked: two syncs at once wait for each other. */
  async lockApiPermissions(): Promise<Permission[]> {
    return this.txHost.tx
      .select()
      .from(permissions)
      .where(this.scoped(eq(permissions.source, 'api')))
      .for('update');
  }

  /** The keys of `keys` that are live, not retired API permissions. */
  async findActiveApiKeys(keys: readonly string[]): Promise<Set<string>> {
    if (keys.length === 0) return new Set();
    const rows = await this.txHost.tx
      .select({ key: permissions.key })
      .from(permissions)
      .where(
        this.scoped(
          eq(permissions.source, 'api'),
          isNull(permissions.retiredAt),
          inArray(permissions.key, [...keys]),
        ),
      );
    return new Set(rows.map((row) => row.key));
  }
}

class SyncRolesRepository extends BaseRepository<typeof roles> {
  constructor(txHost: TransactionHost) {
    super(roles, txHost);
  }

  async findLiveKeys(keys: readonly string[]): Promise<Set<string>> {
    const rows = await this.txHost.tx
      .select({ key: roles.key })
      .from(roles)
      .where(this.scoped(inArray(roles.key, [...keys])));
    return new Set(rows.map((row) => row.key));
  }
}

/**
 * Brings the `permissions` table in step with the registry (D48, D67) and makes
 * sure the system roles exist (D52, D59). Idempotent: a second run changes nothing. Menu
 * permissions are never touched; an API permission is never deleted, only retired. One
 * transaction: the registry lands whole or not at all. Run by `bun run db:migrate` after the
 * migrations, or alone with `bun run db:sync-permissions`.
 */
export const syncPermissions = async (
  registry: readonly PermissionDefinition[],
  txHost: TransactionHost = defaultTxHost,
): Promise<PermissionSyncResult> => {
  const problems = registryProblems(registry);
  if (problems.length > 0) {
    throw new PermissionRegistryError(
      `The permission registry is invalid, nothing was synced:\n${problems.map((p) => `  - ${p}`).join('\n')}`,
    );
  }
  const permissionRepository = new SyncPermissionsRepository(txHost);
  const roleRepository = new SyncRolesRepository(txHost);

  return txHost.run(async (): Promise<PermissionSyncResult> => {
    const result: PermissionSyncResult = {
      added: [],
      updated: [],
      retired: [],
      restored: [],
      rolesCreated: [],
    };

    const existingRoles = await roleRepository.findLiveKeys(SYSTEM_ROLES.map((role) => role.key));
    for (const role of SYSTEM_ROLES) {
      if (existingRoles.has(role.key)) continue;
      await roleRepository.create({ ...role, isSystem: true });
      result.rolesCreated.push(role.key);
    }

    const stored = new Map(
      (await permissionRepository.lockApiPermissions()).map((row) => [row.key, row]),
    );
    for (const entry of registry) {
      const row = stored.get(entry.key);
      if (row === undefined) {
        await permissionRepository.create({
          key: entry.key,
          label: entry.label,
          groupName: entry.group,
          source: 'api',
        });
        result.added.push(entry.key);
        continue;
      }
      const changed = row.label !== entry.label || row.groupName !== entry.group;
      const wasRetired = row.retiredAt !== null;
      if (!changed && !wasRetired) continue;
      await permissionRepository.updateById(row.id, {
        label: entry.label,
        groupName: entry.group,
        retiredAt: null,
      });
      if (wasRetired) result.restored.push(entry.key);
      if (changed) result.updated.push(entry.key);
    }

    const declared = new Set(registry.map((entry) => entry.key));
    for (const row of stored.values()) {
      if (declared.has(row.key) || row.retiredAt !== null) continue;
      await permissionRepository.updateById(row.id, { retiredAt: nowInstant() });
      result.retired.push(row.key);
    }
    return result;
  });
};

/**
 * The registry keys that are not live, unretired API permissions in the database — the server
 * refuses to start while any is left (D49): a route would check a permission nobody can be given.
 */
export const findUnsyncedPermissions = async (
  registry: readonly PermissionDefinition[],
  txHost: TransactionHost = defaultTxHost,
): Promise<string[]> => {
  const keys = registry.map((entry) => entry.key);
  const synced = await new SyncPermissionsRepository(txHost).findActiveApiKeys(keys);
  return keys.filter((key) => !synced.has(key));
};

/** What the server logs before it refuses to start. */
export const unsyncedPermissionsMessage = (keys: readonly string[]): string =>
  `FATAL: ${String(keys.length)} permission(s) of the code are not in the database: ` +
  `${keys.join(', ')}. Run "bun run db:migrate" (or "bun run db:sync-permissions"). Server startup aborted.`;

/** One line per kind of change, for the CLI. */
export const syncSummary = (result: PermissionSyncResult): string => {
  const parts = (
    [
      ['added', result.added],
      ['updated', result.updated],
      ['retired', result.retired],
      ['restored', result.restored],
      ['system roles created', result.rolesCreated],
    ] as const
  )
    .filter(([, keys]) => keys.length > 0)
    .map(([label, keys]) => `${label}: ${keys.join(', ')}`);
  return parts.length === 0
    ? 'Permissions already in sync with the registry, nothing changed'
    : `Permissions synced with the registry — ${parts.join('; ')}`;
};
