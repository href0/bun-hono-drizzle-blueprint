/**
 * Schema conventions (plan step 2.7), checked on every table exported from the schema barrel — the
 * tables drizzle-kit migrates. Each rule is a pure check that returns readable violations; the
 * second half proves every check fires on a deliberately broken table.
 */
import { describe, expect, it } from 'bun:test';
import { is } from 'drizzle-orm';
import {
  bigint,
  getTableConfig,
  PgTable,
  primaryKey,
  serial,
  uniqueIndex,
  uuid,
  varchar,
} from 'drizzle-orm/pg-core';
import * as schema from './index';
import { APPEND_ONLY_TABLES } from './append-only-tables';
import { PERMANENT_UNIQUE_INDEXES } from './permanent-unique-indexes';
import {
  activeUniqueIndex,
  parentReference,
  sequentialPrimaryKey,
  softDelete,
  uuidPrimaryKey,
} from './columns';
import { users } from './domain/users.schema';
import { appTable } from './schemas';

const exportedTables = Object.values(schema as Record<string, unknown>).filter(
  (value): value is PgTable => is(value, PgTable),
);

const columnNames = (columns: readonly unknown[]): string[] =>
  columns.map((column) => (column as { name?: unknown }).name).map(String);

const startsWith = (columns: string[], prefix: string[]): boolean =>
  prefix.every((name, position) => columns[position] === name);

type IdKind = 'uuid' | 'sequential' | 'other';

const idKind = (table: PgTable): IdKind => {
  const config = getTableConfig(table);
  const id = config.columns.find((column) => column.name === 'id');
  if (!id) return 'other';
  const inPrimaryKey =
    id.primary || config.primaryKeys.some((key) => columnNames(key.columns).includes('id'));
  if (!inPrimaryKey) return 'other';
  // uuidPrimaryKey(): generated by the app (UUID v7), no database default.
  if (id.getSQLType() === 'uuid' && id.defaultFn !== undefined && id.default === undefined) {
    return 'uuid';
  }
  // sequentialPrimaryKey() / sequentialId(): bigint GENERATED ALWAYS AS IDENTITY.
  if (id.getSQLType() === 'bigint' && id.generatedIdentity?.type === 'always') return 'sequential';
  return 'other';
};

/** Every violation of the per-table conventions, as "<table>[.<column>]: <rule>". */
const tableViolations = (
  table: PgTable,
  appendOnly: Readonly<Record<string, string>> = APPEND_ONLY_TABLES,
  permanentUniques: Readonly<Record<string, string>> = PERMANENT_UNIQUE_INDEXES,
): string[] => {
  const config = getTableConfig(table);
  const violations: string[] = [];

  // 1. Every foreign key is the leading part of an index (PostgreSQL does not index FKs itself).
  const indexed = [
    ...config.indexes.map((index) => columnNames(index.config.columns)),
    ...config.primaryKeys.map((key) => columnNames(key.columns)),
    ...config.uniqueConstraints.map((constraint) => columnNames(constraint.columns)),
    ...config.columns.filter((column) => column.primary || column.isUnique).map((c) => [c.name]),
  ];
  for (const foreignKey of config.foreignKeys) {
    const columns = columnNames(foreignKey.reference().columns);
    if (!indexed.some((index) => startsWith(index, columns))) {
      violations.push(
        `${config.name}.${columns.join(',')}: foreign key without an index starting with it`,
      );
    }
  }

  // 2–3. Ids come from the helpers; sequential ids only for APPEND_ONLY_TABLES.
  const kind = idKind(table);
  if (kind === 'other') {
    violations.push(
      `${config.name}.id: not from uuidPrimaryKey() (or sequentialPrimaryKey() for APPEND_ONLY_TABLES)`,
    );
  }
  if (kind === 'sequential' && !(config.name in appendOnly)) {
    violations.push(`${config.name}: sequential id but not listed in APPEND_ONLY_TABLES`);
  }

  // 4. No serial columns (identity instead, through the helpers).
  for (const column of config.columns) {
    if (/serial/i.test(column.getSQLType())) {
      violations.push(`${config.name}.${column.name}: serial column (use the column helpers)`);
    }
  }

  // 5. Soft-deleted tables: uniqueness only among live rows (activeUniqueIndex), except the
  //    named indexes in PERMANENT_UNIQUE_INDEXES.
  if (config.columns.some((column) => column.name === 'deleted_at')) {
    const plainUniques = [
      ...config.columns.filter((column) => column.isUnique).map((column) => column.name),
      ...config.uniqueConstraints.map((constraint) => columnNames(constraint.columns).join(',')),
      ...config.indexes
        .filter((index) => index.config.unique && index.config.where === undefined)
        .filter((index) => !Object.hasOwn(permanentUniques, index.config.name ?? ''))
        .map((index) => index.config.name ?? columnNames(index.config.columns).join(',')),
    ];
    for (const unique of plainUniques) {
      violations.push(
        `${config.name}: plain unique (${unique}) on a soft-deleted table — use activeUniqueIndex()`,
      );
    }
  }

  return violations;
};

/** Allowlist entries must name an exported table that really uses a sequential id. */
const staleAllowlistEntries = (
  tables: PgTable[],
  appendOnly: Readonly<Record<string, string>> = APPEND_ONLY_TABLES,
): string[] =>
  Object.keys(appendOnly)
    .filter((name) => {
      const table = tables.find((candidate) => getTableConfig(candidate).name === name);
      return !table || idKind(table) !== 'sequential';
    })
    .map(
      (name) => `APPEND_ONLY_TABLES.${name}: stale entry (no exported table with a sequential id)`,
    );

/** Names of the plain unique indexes on soft-deleted tables (what the allowlist may name). */
const plainUniqueIndexNames = (tables: PgTable[]): string[] =>
  tables
    .map((table) => getTableConfig(table))
    .filter((config) => config.columns.some((column) => column.name === 'deleted_at'))
    .flatMap((config) => config.indexes)
    .filter((index) => index.config.unique && index.config.where === undefined)
    .map((index) => index.config.name ?? '');

/** Allowlist entries must name a plain unique index of a soft-deleted exported table. */
const stalePermanentUniqueEntries = (
  tables: PgTable[],
  permanentUniques: Readonly<Record<string, string>> = PERMANENT_UNIQUE_INDEXES,
): string[] => {
  const existing = plainUniqueIndexNames(tables);
  return Object.keys(permanentUniques)
    .filter((name) => !existing.includes(name))
    .map(
      (name) =>
        `PERMANENT_UNIQUE_INDEXES.${name}: stale entry (no plain unique index of that name on a soft-deleted table)`,
    );
};

describe('schema conventions (every exported table)', () => {
  it('finds the exported tables (guards the enumeration itself)', () => {
    expect(exportedTables.map((table) => getTableConfig(table).name)).toEqual(
      expect.arrayContaining(['auth_refresh_tokens', 'record_changes', 'users']),
    );
  });

  it('hold for every table', () => {
    expect(exportedTables.flatMap((table) => tableViolations(table))).toEqual([]);
  });

  it('keep APPEND_ONLY_TABLES free of stale entries', () => {
    expect(staleAllowlistEntries(exportedTables)).toEqual([]);
  });

  it('keep PERMANENT_UNIQUE_INDEXES free of stale entries', () => {
    expect(stalePermanentUniqueEntries(exportedTables)).toEqual([]);
  });

  it('keep record_changes partition-ready', () => {
    const config = getTableConfig(schema.recordChanges);
    expect(config.primaryKeys.map((key) => columnNames(key.columns))).toEqual([
      ['id', 'changed_at'],
    ]);
    expect(config.foreignKeys).toEqual([]);
    expect(config.uniqueConstraints).toEqual([]);
    expect(config.indexes.filter((index) => index.config.unique)).toEqual([]);
    expect(config.checks.map((check) => check.name).sort()).toEqual([
      'record_changes_action_check',
      'record_changes_parent_check',
    ]);
  });
});

describe('auth_refresh_tokens (plan L3)', () => {
  const config = getTableConfig(schema.authRefreshTokens);
  const leadingColumns = config.indexes.map((index) => columnNames(index.config.columns).at(0));

  it('indexes user_id (foreign key) and family_id (reuse detection revokes a whole family)', () => {
    expect(leadingColumns).toEqual(expect.arrayContaining(['user_id', 'family_id']));
    expect(columnNames(config.foreignKeys.flatMap((key) => key.reference().columns))).toEqual([
      'user_id',
    ]);
  });

  it('finds a token only by its unique SHA-256 hex', () => {
    const tokenHash = config.columns.find((column) => column.name === 'token_hash');

    expect(tokenHash?.getSQLType()).toBe('char(64)');
    expect(tokenHash?.isUnique).toBe(true);
    expect(config.columns.map((column) => column.name)).not.toContain('token');
  });
});

describe('the convention checks fire on broken tables', () => {
  it('foreign key without an index → names table and column', () => {
    const table = appTable('bad_details', {
      id: uuidPrimaryKey(),
      headerId: parentReference('header_id', () => users.id),
    });

    expect(tableViolations(table)).toEqual([
      'bad_details.header_id: foreign key without an index starting with it',
    ]);
  });

  it('an index that does not START with the foreign key does not count', () => {
    const table = appTable(
      'bad_details',
      {
        id: uuidPrimaryKey(),
        code: varchar('code', { length: 10 }).notNull(),
        headerId: parentReference('header_id', () => users.id),
      },
      (t) => [uniqueIndex('bad_details_code_header_uq').on(t.code, t.headerId)],
    );

    expect(tableViolations(table)).toEqual([
      'bad_details.header_id: foreign key without an index starting with it',
    ]);
  });

  it('sequential id outside APPEND_ONLY_TABLES → names the table', () => {
    const table = appTable('bad_events', { id: sequentialPrimaryKey() });

    expect(tableViolations(table)).toEqual([
      'bad_events: sequential id but not listed in APPEND_ONLY_TABLES',
    ]);
    expect(tableViolations(table, { bad_events: 'reason' })).toEqual([]);
  });

  it('an id not built with the helpers', () => {
    const plainUuid = appTable('bad_uuid', { id: uuid('id').primaryKey() });
    const plainBigint = appTable('bad_bigint', {
      id: bigint('id', { mode: 'number' }).primaryKey(),
    });

    expect(tableViolations(plainUuid)).toEqual([
      'bad_uuid.id: not from uuidPrimaryKey() (or sequentialPrimaryKey() for APPEND_ONLY_TABLES)',
    ]);
    expect(tableViolations(plainBigint)).toEqual([
      'bad_bigint.id: not from uuidPrimaryKey() (or sequentialPrimaryKey() for APPEND_ONLY_TABLES)',
    ]);
  });

  it('serial columns', () => {
    const table = appTable('bad_serial', { id: uuidPrimaryKey(), number: serial('number') });

    expect(tableViolations(table)).toEqual([
      'bad_serial.number: serial column (use the column helpers)',
    ]);
  });

  it('plain unique on a soft-deleted table; activeUniqueIndex passes', () => {
    const plain = appTable('bad_soft', {
      id: uuidPrimaryKey(),
      code: varchar('code', { length: 10 }).notNull().unique(),
      ...softDelete(),
    });
    const active = appTable(
      'good_soft',
      { id: uuidPrimaryKey(), code: varchar('code', { length: 10 }).notNull(), ...softDelete() },
      (t) => [activeUniqueIndex('good_soft_code_uq', [t.code], t.deletedAt)],
    );

    expect(tableViolations(plain)).toEqual([
      'bad_soft: plain unique (code) on a soft-deleted table — use activeUniqueIndex()',
    ]);
    expect(tableViolations(active)).toEqual([]);
  });

  it('plain unique index on a soft-deleted table: exempt only when named in the allowlist', () => {
    const table = appTable(
      'perm_soft',
      { id: uuidPrimaryKey(), code: varchar('code', { length: 10 }).notNull(), ...softDelete() },
      (t) => [uniqueIndex('perm_soft_code_uq').on(t.code)],
    );
    const violation =
      'perm_soft: plain unique (perm_soft_code_uq) on a soft-deleted table — use activeUniqueIndex()';

    expect(tableViolations(table)).toEqual([violation]);
    expect(tableViolations(table, APPEND_ONLY_TABLES, { perm_soft_code_uq: 'reason' })).toEqual([]);
    expect(tableViolations(table, APPEND_ONLY_TABLES, { other_uq: 'reason' })).toEqual([violation]);
  });

  it('stale PERMANENT_UNIQUE_INDEXES entries', () => {
    expect(
      stalePermanentUniqueEntries(exportedTables, { ...PERMANENT_UNIQUE_INDEXES, gone_uq: 'x' }),
    ).toEqual([
      'PERMANENT_UNIQUE_INDEXES.gone_uq: stale entry (no plain unique index of that name on a soft-deleted table)',
    ]);
    // An activeUniqueIndex is not a plain unique, so listing one is stale too.
    expect(stalePermanentUniqueEntries(exportedTables, { users_email_active_uq: 'x' })).toEqual([
      'PERMANENT_UNIQUE_INDEXES.users_email_active_uq: stale entry (no plain unique index of that name on a soft-deleted table)',
    ]);
  });

  it('stale APPEND_ONLY_TABLES entries', () => {
    expect(staleAllowlistEntries(exportedTables, { ...APPEND_ONLY_TABLES, gone: 'x' })).toEqual([
      'APPEND_ONLY_TABLES.gone: stale entry (no exported table with a sequential id)',
    ]);
    expect(staleAllowlistEntries(exportedTables, { users: 'not sequential' })).toEqual([
      'APPEND_ONLY_TABLES.users: stale entry (no exported table with a sequential id)',
    ]);
  });

  it('accepts an FK covered by an index, a unique column or a composite primary key', () => {
    const viaIndex = appTable(
      'good_details',
      { id: uuidPrimaryKey(), headerId: parentReference('header_id', () => users.id) },
      (t) => [uniqueIndex('good_details_header_uq').on(t.headerId)],
    );
    const viaUniqueColumn = appTable('good_profiles', {
      id: uuidPrimaryKey(),
      userId: parentReference('user_id', () => users.id).unique(),
    });
    const viaPrimaryKey = appTable(
      'good_links',
      {
        userId: parentReference('user_id', () => users.id),
        id: uuidPrimaryKey(),
      },
      (t) => [primaryKey({ columns: [t.userId, t.id] })],
    );

    expect(tableViolations(viaIndex)).toEqual([]);
    expect(tableViolations(viaUniqueColumn)).toEqual([]);
    expect(tableViolations(viaPrimaryKey).filter((v) => v.includes('foreign key'))).toEqual([]);
  });
});
