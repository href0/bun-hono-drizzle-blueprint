import { describe, expect, it } from 'bun:test';
import { getTableConfig, PgDialect, type PgColumn } from 'drizzle-orm/pg-core';
import { Temporal } from 'temporal-polyfill';
import { APPEND_ONLY_TABLES } from './append-only-tables';
import {
  activeUniqueIndex,
  auditColumns,
  calendarDate,
  instant,
  parentReference,
  sequentialPrimaryKey,
  softDelete,
  timestamps,
  timeZoneColumn,
  uuidPrimaryKey,
} from './columns';
import { recordChanges } from './domain/record-changes.schema';
import { users } from './domain/users.schema';
import { appTable } from './schemas';

const UUID_V7 = /^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

const headers = appTable('test_headers', { id: uuidPrimaryKey() });
const details = appTable(
  'test_details',
  {
    id: uuidPrimaryKey(),
    headerId: parentReference('header_id', () => headers.id),
    code: timeZoneColumn('code'),
    dueDate: calendarDate('due_date'),
    plannedAt: instant('planned_at'),
    ...timestamps(),
    ...auditColumns(),
    ...softDelete(),
  },
  (table) => [activeUniqueIndex('test_details_code_active_uq', [table.code], table.deletedAt)],
);
const records = appTable('test_records', { id: sequentialPrimaryKey() });

const column = (table: typeof details, name: string): PgColumn => {
  const found = getTableConfig(table).columns.find((candidate) => candidate.name === name);
  if (!found) throw new Error(`column ${name} not found`);
  return found;
};

describe('uuidPrimaryKey', () => {
  it('is a uuid primary key generated by the app as UUID v7, with no database default', () => {
    const id = getTableConfig(users).columns.find((candidate) => candidate.name === 'id');
    expect(id?.primary).toBe(true);
    expect(id?.getSQLType()).toBe('uuid');
    expect(id?.hasDefault).toBe(true);
    expect(id?.default).toBeUndefined();
    const generated = id?.defaultFn?.();
    expect(String(generated)).toMatch(UUID_V7);
  });
});

describe('sequentialPrimaryKey', () => {
  it('is a bigint identity in number mode (JSON-safe)', () => {
    const id = getTableConfig(records).columns.at(0);
    expect(id?.getSQLType()).toBe('bigint');
    expect(id?.primary).toBe(true);
    expect(id?.generatedIdentity?.type).toBe('always');
    expect(id?.dataType).toBe('number');
  });

  it('is allowed only for tables listed in APPEND_ONLY_TABLES, each with a reason', () => {
    // The platform's record tables; a project adds its own (`bun run scaffold … --variant=record`).
    // That every entry is an exported table with a sequential key is schema-conventions.test.ts.
    expect(Object.keys(APPEND_ONLY_TABLES)).toEqual(
      expect.arrayContaining(['record_changes', 'webhook_events']),
    );
    expect(Object.values(APPEND_ONLY_TABLES).every((reason) => reason.trim().length > 0)).toBe(
      true,
    );
  });
});

describe('sequentialId', () => {
  it('is the same bigint identity without a primary key (composite, partition-ready keys)', () => {
    const id = getTableConfig(recordChanges).columns.find((candidate) => candidate.name === 'id');
    expect(id?.getSQLType()).toBe('bigint');
    expect(id?.primary).toBe(false);
    expect(id?.generatedIdentity?.type).toBe('always');
    expect(id?.dataType).toBe('number');
    expect(
      getTableConfig(recordChanges)
        .primaryKeys.at(0)
        ?.columns.map((c) => c.name),
    ).toEqual(['id', 'changed_at']);
  });
});

describe('instant()', () => {
  const plannedAt = column(details, 'planned_at');

  it('maps timestamptz text from the driver to Temporal.Instant, keeping microseconds', () => {
    const value = plannedAt.mapFromDriverValue('2026-10-05 10:00:00.123456+07') as Temporal.Instant;
    expect(value).toBeInstanceOf(Temporal.Instant);
    expect(value.toString()).toBe('2026-10-05T03:00:00.123456Z');
  });

  it('writes ISO 8601 UTC with full precision', () => {
    const value = Temporal.Instant.from('2026-10-05T03:00:00.123456Z');
    expect(plannedAt.mapToDriverValue(value)).toBe('2026-10-05T03:00:00.123456Z');
    expect(plannedAt.getSQLType()).toBe('timestamp with time zone');
  });
});

describe('calendarDate()', () => {
  const dueDate = column(details, 'due_date');

  it('maps date text to Temporal.PlainDate and back', () => {
    const value = dueDate.mapFromDriverValue('2026-10-05') as Temporal.PlainDate;
    expect(value).toBeInstanceOf(Temporal.PlainDate);
    expect(dueDate.mapToDriverValue(value)).toBe('2026-10-05');
    expect(dueDate.getSQLType()).toBe('date');
  });
});

describe('timestamps / auditColumns / softDelete / timeZoneColumn', () => {
  it('created_at / updated_at default to now() and updated_at refreshes on update', () => {
    const createdAt = column(details, 'created_at');
    const updatedAt = column(details, 'updated_at');
    expect(createdAt.notNull).toBe(true);
    expect(createdAt.hasDefault).toBe(true);
    // A value, not NOW: drizzle-orm binds $onUpdate results as parameters (see timestamps()).
    expect(updatedAt.onUpdateFn?.()).toBeInstanceOf(Temporal.Instant);
  });

  it('audit columns are required varchar(150); deleted_at is a nullable instant', () => {
    expect(column(details, 'created_by').getSQLType()).toBe('varchar(150)');
    expect(column(details, 'updated_by').notNull).toBe(true);
    expect(column(details, 'deleted_at').notNull).toBe(false);
    expect(column(details, 'deleted_at').getSQLType()).toBe('timestamp with time zone');
  });

  it('time zone names fit varchar(64)', () => {
    expect(column(details, 'code').getSQLType()).toBe('varchar(64)');
  });
});

describe('parentReference / activeUniqueIndex', () => {
  it('references the parent id and refuses deleting a parent that has children', () => {
    const foreignKey = getTableConfig(details).foreignKeys.at(0);
    const reference = foreignKey?.reference();
    expect(reference?.columns.map((col) => col.name)).toEqual(['header_id']);
    expect(reference?.foreignColumns.map((col) => col.name)).toEqual(['id']);
    expect(foreignKey?.onDelete).toBe('restrict');
    expect(column(details, 'header_id').notNull).toBe(true);
  });

  it('is a unique index over live rows only (WHERE deleted_at IS NULL)', () => {
    const index = getTableConfig(details).indexes.at(0);
    expect(index?.config.unique).toBe(true);
    expect(index?.config.name).toBe('test_details_code_active_uq');
    const where = index?.config.where;
    if (!where) throw new Error('missing partial index condition');
    expect(new PgDialect().sqlToQuery(where).sql).toBe('"deleted_at" is null');
  });
});
