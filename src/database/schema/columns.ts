import { sql, type SQL } from 'drizzle-orm';
import {
  bigint,
  customType,
  uniqueIndex,
  uuid,
  varchar,
  type AnyPgColumn,
  type IndexColumn,
} from 'drizzle-orm/pg-core';
import type { Temporal } from 'temporal-polyfill';
import { nowInstant, parseCalendarDate, parseInstant } from '../../utils/datetime.util';

/**
 * Column helpers — the only way tables declare ids, timestamps, audit and soft-delete columns
 * (ESLint bans raw `timestamp(` / `date(` / `serial(` / `pgTable(` in schema files; the schema
 * convention test of plan step 2.7 checks ids and indexes).
 */

// ---------------------------------------------------------------------------------------------
// Primary keys
// ---------------------------------------------------------------------------------------------

/**
 * Default primary key: UUID v7, generated by the application (`Bun.randomUUIDv7()` — PostgreSQL 16
 * has no `uuidv7()`). Time-ordered, so B-tree inserts stay at the right edge like a sequence, yet
 * ids are not guessable. Raw SQL inserts must supply `id` themselves.
 */
export const uuidPrimaryKey = () =>
  uuid('id')
    .primaryKey()
    .$defaultFn(() => Bun.randomUUIDv7());

/**
 * `bigint` identity key — **only** for high-volume append-only tables listed in
 * `APPEND_ONLY_TABLES` (`append-only-tables.ts`), e.g. audit trails and logs. Never exposed as a
 * public resource id (sequential ids invite enumeration). `mode: 'number'` because a JS `bigint`
 * breaks `JSON.stringify`; safe up to 2^53.
 */
export const sequentialPrimaryKey = () => sequentialId().primaryKey();

/**
 * The same `bigint` identity without a primary key, for append-only tables whose primary key also
 * holds the partition key — `PRIMARY KEY (id, changed_at)` on `record_changes`, so the table can
 * later be partitioned by time. Same `APPEND_ONLY_TABLES` restriction.
 */
export const sequentialId = () => bigint('id', { mode: 'number' }).generatedAlwaysAsIdentity();

// ---------------------------------------------------------------------------------------------
// Time (plan D13 — see .agents/skills/project-standards/references/datetime.md)
// ---------------------------------------------------------------------------------------------

/**
 * `timestamptz` ⇄ `Temporal.Instant`. The driver hands timestamps over as PostgreSQL text
 * (`2026-10-05 03:00:00.123456+00`), which `parseInstant` reads with full microsecond precision;
 * values are written as ISO 8601 UTC.
 */
const instantColumn = customType<{ data: Temporal.Instant; driverData: string }>({
  dataType: () => 'timestamp with time zone',
  fromDriver: (value) => parseInstant(value),
  toDriver: (value) => value.toString(),
});

/** `date` ⇄ `Temporal.PlainDate` (`YYYY-MM-DD`, no time zone). */
const calendarDateColumn = customType<{ data: Temporal.PlainDate; driverData: string }>({
  dataType: () => 'date',
  fromDriver: (value) => parseCalendarDate(value),
  toDriver: (value) => value.toString(),
});

/** An exact moment (`*_at`). */
export const instant = (name: string) => instantColumn(name);

/** A day with no time zone (`*_date`). */
export const calendarDate = (name: string) => calendarDateColumn(name);

/** The IANA zone a local schedule was planned in (`*_timezone`), validated by `timeZoneField`. */
export const timeZoneColumn = (name: string) => varchar(name, { length: 64 });

const NOW: SQL = sql`now()`;

/** `created_at` / `updated_at`: set by the database on insert; `updated_at` refreshed on update. */
export const timestamps = () => ({
  createdAt: instant('created_at').notNull().default(NOW),
  updatedAt: instant('updated_at').notNull().default(NOW).$onUpdate(nowInstant),
});

// ---------------------------------------------------------------------------------------------
// Audit & soft delete
// ---------------------------------------------------------------------------------------------

/**
 * Who created / last changed the row: the request actor (`user:<id>`, `partner:<code>`, `system`).
 * Filled by the base repository (plan step 2.5), never by callers.
 */
export const auditColumns = () => ({
  createdBy: varchar('created_by', { length: 150 }).notNull(),
  updatedBy: varchar('updated_by', { length: 150 }).notNull(),
});

/** Soft delete: rows with `deleted_at` set are invisible to the base repository (plan step 2.5). */
export const softDelete = () => ({
  deletedAt: instant('deleted_at'),
});

/**
 * Uniqueness among live rows only, so a soft-deleted row never blocks re-creating the same value:
 * `CREATE UNIQUE INDEX … WHERE deleted_at IS NULL`. Tables with `softDelete()` must use this
 * instead of `.unique()` (checked by the schema convention test).
 */
export const activeUniqueIndex = (
  name: string,
  columns: [IndexColumn, ...IndexColumn[]],
  deletedAt: AnyPgColumn,
) =>
  uniqueIndex(name)
    .on(...columns)
    // Unqualified column name: an index predicate may only reference its own table, and some
    // PostgreSQL versions reject schema-qualified column references there.
    .where(sql`${sql.identifier(deletedAt.name)} is null`);

// ---------------------------------------------------------------------------------------------
// Relations
// ---------------------------------------------------------------------------------------------

/**
 * Foreign key to a parent row (detail → header). Deleting a parent that still has children is
 * refused (`restrict`). Declare an index starting with this column in the table's extra config —
 * the schema convention test fails without it.
 */
export const parentReference = (name: string, parentId: () => AnyPgColumn) =>
  uuid(name).notNull().references(parentId, { onDelete: 'restrict' });
